/* ============================================================
   作业2  第3小题：用 C 语言实现
   输出 ASCII 表的小写字母，每行 13 个字符
   ============================================================ */

#include <stdio.h>

int main(void)
{
    int i;

    for (i = 0; i < 26; i++) {
        putchar('a' + i);          /* 输出当前字母 */
        if ((i + 1) % 13 == 0)     /* 每输出 13 个换一行 */
            putchar('\n');
    }

    return 0;
}
